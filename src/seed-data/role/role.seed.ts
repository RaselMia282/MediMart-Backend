// prisma/seed.ts

import { prisma } from "../../lib/prisma";

async function main() {
  const roles = ["CUSTOMER", "VENDOR", "ADMIN"];

  for (const name of roles) {
    await prisma.role.upsert({
      where: { name },
      update: {},
      create: { name },
    });
  }

  console.log("Default roles seeded successfully");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
